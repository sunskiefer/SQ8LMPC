#!/usr/bin/env python3
"""Single source of the SQ8LMPC parameter list.

Writes params.json (the wrapper's input) and src/sq8lmpc/param_table.inc (the engine's key table).
The order is the VST parameter index: append only, never reorder (params.lock enforces it)."""
import json, os, sys

ROOT = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))

# (key, label, original page tag) -- the panel's page buttons, tags from the original editor
PAGE_BUTTONS = [
    ("osc1", "OSC 1", 16), ("osc2", "OSC 2", 32), ("osc3", "OSC 3", 48),
    ("dca1", "DCA 1", 17), ("dca2", "DCA 2", 33), ("dca3", "DCA 3", 49),
    ("filt", "FILTER", 64), ("dca4", "DCA 4", 80), ("modes", "MODES", 287),
    ("lfo1", "LFO 1", 111), ("lfo2", "LFO 2", 127), ("lfo3", "LFO 3", 143), ("lfo4", "LFO 4", 159),
    ("env1", "ENV 1", 175), ("env2", "ENV 2", 191), ("env3", "ENV 3", 207), ("env4", "ENV 4", 223),
    ("mat1", "MATRIX 1", 224), ("mat2", "MATRIX 2", 240), ("mat3", "MATRIX 3", 256),
    ("wav", "WAVES", 15),
]
# actions (momentary buttons)
ACTIONS = [
    ("up", "PRG +"), ("down", "PRG -"), ("bank", "BANK"), ("write", "WRITE"), ("init", "INIT"),
    ("sync", "SYNC"), ("am", "AM"), ("mono", "MONO"), ("pgup", "PAGE UP"), ("pgdn", "PAGE DN"),
    ("load", "LOAD"), ("export", "EXPORT"),
]
LEDS = [("led_sync", "SYNC LED"), ("led_am", "AM LED"), ("led_mono", "MONO LED"),
        ("led_pgup", "PAGE UP LIT"), ("led_pgdn", "PAGE DN LIT")]
VFD_COLS, VFD_ROWS = 44, 2
VFD_FRAMES = 272          # 68 glyphs x 4 attributes
NUM_CELLS, NUM_FRAMES = 4, 17

def build():
    P, T = [], []   # params, table rows (key, kind, arg)
    def add(p, kind, arg=0):
        P.append(p); T.append((p["key"], kind, arg))
    add({"key": "program", "name": "PROGRAM", "display": "int", "min": 0, "max": 511, "default": 256,
         "nudge_pct": 10, "refresh_display": True}, "PROGRAM")
    for i in range(10):
        add({"key": "k%d" % i, "name": "KNOB %d" % (i + 1), "default": 0.5, "min": 0, "max": 1,
             "dynamic_name": True, "dynamic_display": True}, "KNOB", i)
    for key, label, tag in PAGE_BUTTONS:
        add({"key": "pg_" + key, "name": label, "momentary": True, "min": 0, "max": 1, "default": 0,
             "refresh_display": True}, "PAGE", tag)
    for n, (key, label) in enumerate(ACTIONS):
        add({"key": "b_" + key, "name": label, "momentary": True, "min": 0, "max": 1, "default": 0,
             "refresh_display": True}, "ACTION", n)
    for n, (key, label) in enumerate(LEDS):
        add({"key": key, "name": label, "options": ["OFF", "ON"], "default": 0}, "LED", n)
    for r in range(VFD_ROWS):
        for c in range(VFD_COLS):
            add({"key": "c%d_%02d" % (r, c), "name": "VFD %d.%02d" % (r + 1, c + 1), "min": 0, "max": 1, "default": 0},
                "CELL", r * VFD_COLS + c)
    for i in range(NUM_CELLS):
        add({"key": "n%d" % i, "name": "NUM %d" % (i + 1), "min": 0, "max": 1, "default": 0}, "NUM", i)
    add({"key": "pname", "name": "PROGRAM NAME", "display": "string", "min": 0, "max": 1, "default": 0}, "PNAME")
    add({"key": "pack", "name": "BANK SET", "display": "string", "min": 0, "max": 1, "default": 0}, "PACK")
    return P, T

def main():
    P, T = build()
    json.dump({"params": P}, open(os.path.join(ROOT, "params.json"), "w"), indent=1)
    kinds = sorted({k for _, k, _ in T})
    with open(os.path.join(ROOT, "src/sq8lmpc/param_table.inc"), "w") as f:
        f.write("// generated by tools/gen_params.py -- do not edit\n")
        for n, k in enumerate(kinds): f.write("// kind %s\n" % k)
        for key, kind, arg in T:
            f.write('{"%s", PK_%s, %d},\n' % (key, kind, arg))
    print("params:", len(P))

main()
